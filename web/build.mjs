// Builds the frontend into web/dist.
//
// Plugin frontends (plugins/*/web/index.ts) are discovered automatically and
// bundled together with the core, so installing a plugin + rebuilding is all
// that is needed. Output file names contain a content hash (cache busting).
import * as esbuild from 'esbuild';
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const pluginsDir = path.resolve(here, '..', 'plugins');
const dist = path.join(here, 'dist');
const watch = process.argv.includes('--watch');

function generatePluginImports() {
  const dirs = fs.existsSync(pluginsDir) ? fs.readdirSync(pluginsDir).sort() : [];
  const lines = ['// Generated by build.mjs - do not edit.', '// Imports the frontend part of every installed plugin.', 'import { definePluginModule } from "../coreplugin";', ''];
  const mods = [];
  for (const d of dirs) {
    const entry = path.join(pluginsDir, d, 'web', 'index.ts');
    const manifest = path.join(pluginsDir, d, 'plugin.json');
    if (!fs.existsSync(entry) || !fs.existsSync(manifest)) continue;
    const id = JSON.parse(fs.readFileSync(manifest, 'utf8')).id;
    const name = 'p_' + d.replace(/[^a-zA-Z0-9_]/g, '_');
    lines.push(`import * as ${name} from "../../../plugins/${d}/web/index";`);
    mods.push(`  definePluginModule(${JSON.stringify(id)}, ${name}),`);
  }
  lines.push('', 'export const pluginModules = [', ...mods, '];', '');
  fs.mkdirSync(path.join(here, 'src', 'generated'), { recursive: true });
  fs.writeFileSync(path.join(here, 'src', 'generated', 'plugins.ts'), lines.join('\n'));
}

const options = {
  entryPoints: [path.join(here, 'src', 'main.ts')],
  bundle: true,
  minify: !watch,
  sourcemap: watch ? 'inline' : false,
  format: 'esm',
  // rarely used, large parts (the visual editor) are loaded on first use
  splitting: true,
  chunkNames: 'chunks/[name]-[hash]',
  target: ['es2022', 'chrome111', 'firefox115', 'safari16'],
  outdir: path.join(dist, 'assets'),
  entryNames: 'app',
  alias: { '@ewiki/coreplugin': path.join(here, 'src', 'coreplugin.ts') },
  legalComments: 'none',
  // fonts referenced from CSS (e.g. the website template) are copied with a content hash
  loader: { '.woff2': 'file' },
  assetNames: '[name]-[hash]',
  logLevel: 'info',
  metafile: true,
};

// The npm packages that end up in the bundle (for the third-party notices:
// tools/notices includes exactly their license texts).
function writeBundledPackages(...metas) {
  const pkgs = new Set();
  for (const input of metas.filter(Boolean).flatMap((m) => Object.keys(m.inputs))) {
    const m = /node_modules\/((?:@[^/]+\/)?[^/]+)\//.exec(input.slice(input.lastIndexOf('node_modules/')));
    if (m) pkgs.add(input.slice(0, input.lastIndexOf('node_modules/')) + 'node_modules/' + m[1]);
  }
  pkgs.add(iconsPkg); // the icons are shipped as files, not bundled
  const list = [...pkgs].map((p) => path.relative(here, path.resolve(here, p))).sort();
  fs.mkdirSync(path.join(here, '.build'), { recursive: true });
  fs.writeFileSync(path.join(here, '.build', 'bundled-packages.json'), JSON.stringify(list, null, 1) + '\n');
}

function writeIndex(meta) {
  const js = fs.readFileSync(path.join(dist, 'assets', 'app.js'));
  const css = fs.existsSync(path.join(dist, 'assets', 'app.css')) ? fs.readFileSync(path.join(dist, 'assets', 'app.css')) : Buffer.from('');
  const h = (b) => createHash('sha256').update(b).digest('hex').slice(0, 10);
  const jsName = `app-${h(js)}.js`, cssName = `app-${h(css)}.css`;
  for (const f of fs.readdirSync(path.join(dist, 'assets'))) {
    if (/^app-[0-9a-f]{10}\.(js|css)$/.test(f)) fs.rmSync(path.join(dist, 'assets', f));
  }
  fs.renameSync(path.join(dist, 'assets', 'app.js'), path.join(dist, 'assets', jsName));
  if (css.length) fs.renameSync(path.join(dist, 'assets', 'app.css'), path.join(dist, 'assets', cssName));
  // chunks app.js imports directly are preloaded (no request waterfall)
  const entry = meta && Object.entries(meta.outputs).find(([, o]) => o.entryPoint && o.entryPoint.endsWith('src/main.ts'));
  const preload = (entry ? entry[1].imports : []).filter((i) => i.kind === 'import-statement')
    .map((i) => `<link rel="modulepreload" href="/assets/${path.relative(path.join(dist, 'assets'), path.resolve(i.path)).split(path.sep).join('/')}">`).join('\n  ');
  const html = fs.readFileSync(path.join(here, 'index.html'), 'utf8')
    .replace('%CSS%', `/assets/${cssName}`).replace('%JS%', `/assets/${jsName}`)
    .replace('%PRELOAD%', preload);
  fs.writeFileSync(path.join(dist, 'index.html'), html);
  fs.writeFileSync(path.join(dist, '.gitkeep'), '');
}

// The icons (a free set, MIT): one small file per icon under
// assets/icons/<version>/ (cached for good, the version is in the path) and
// an index with names, categories and search words for the picker. They are
// not part of the bundle; a page loads only the icons it shows.
const iconsPkg = path.join(here, 'node_modules', '@tabler', 'icons');
function iconVersion() {
  return JSON.parse(fs.readFileSync(path.join(iconsPkg, 'package.json'), 'utf8')).version;
}
function generateIconsModule() {
  const v = iconVersion();
  fs.mkdirSync(path.join(here, 'src', 'generated'), { recursive: true });
  fs.writeFileSync(path.join(here, 'src', 'generated', 'icons.ts'), `// Generated by build.mjs - do not edit.\nexport const ICON_BASE = ${JSON.stringify(`/assets/icons/${v}`)};\n`);
}
function copyIcons() {
  const v = iconVersion();
  const out = path.join(dist, 'assets', 'icons', v);
  const meta = JSON.parse(fs.readFileSync(path.join(iconsPkg, 'icons.json'), 'utf8'));
  const index = [];
  for (const style of ['outline', 'filled']) {
    const from = path.join(iconsPkg, 'icons', style);
    fs.mkdirSync(path.join(out, style), { recursive: true });
    for (const f of fs.readdirSync(from)) {
      if (!/^[a-z0-9-]+\.svg$/.test(f)) continue;
      // minified, without the class of the set (only shapes and their stroke)
      const svg = fs.readFileSync(path.join(from, f), 'utf8').replace(/\s+class="[^"]*"/, '').replace(/\s*\n\s*/g, ' ').replace(/>\s+</g, '><').trim();
      fs.writeFileSync(path.join(out, style, f), svg);
    }
  }
  for (const [name, m] of Object.entries(meta)) {
    const styles = Object.keys(m.styles ?? {}).filter((st) => fs.existsSync(path.join(out, st, `${name}.svg`)));
    if (!styles.length) continue;
    index.push({ n: name, c: m.category || '', t: (m.tags ?? []).slice(0, 12).map(String), s: styles.map((st) => st[0]).join('') });
  }
  fs.writeFileSync(path.join(out, 'index.json'), JSON.stringify(index));
  // search words and category names in other languages (src/icons/terms/<lang>.json),
  // loaded by the picker only in that language
  const termsDir = path.join(here, 'src', 'icons', 'terms');
  for (const f of fs.readdirSync(termsDir)) {
    const m = /^([a-z]{2,3})\.json$/.exec(f);
    if (!m) continue;
    const terms = JSON.parse(fs.readFileSync(path.join(termsDir, f), 'utf8'));
    fs.writeFileSync(path.join(out, `terms.${m[1]}.json`), JSON.stringify({ categories: terms.categories ?? {}, words: terms.words ?? {} }));
  }
}

// The frame that draws diagrams from text (Mermaid): one classic script
// (an iframe without its own origin loads no modules), its own page
// diagram-frame.html that the server sends with a strict CSP. elkjs is
// replaced by a stub: its licence (EPL-2.0 or GPL) is not shipped.
async function buildDiagramFrame() {
  const out = path.join(dist, 'assets', 'diagram');
  const r = await esbuild.build({
    entryPoints: [path.join(here, 'src', 'diagram', 'frame.ts')],
    bundle: true, minify: true, format: 'iife', write: false, metafile: true, legalComments: 'none',
    target: ['es2022', 'chrome111', 'firefox115', 'safari16'],
    outfile: path.join(out, 'frame.js'),
    plugins: [{ name: 'no-elk', setup(b) { b.onResolve({ filter: /^elkjs(\/|$)/ }, () => ({ path: path.join(here, 'src', 'diagram', 'elk-stub.ts') })); } }],
    logLevel: 'error',
  });
  if (Object.keys(r.metafile.inputs).some((i) => i.includes('node_modules/elkjs/'))) throw new Error('elkjs must not be bundled');
  const js = r.outputFiles[0].contents;
  const name = `frame-${createHash('sha256').update(js).digest('hex').slice(0, 10)}.js`;
  fs.mkdirSync(out, { recursive: true });
  fs.writeFileSync(path.join(out, name), js);
  const html = fs.readFileSync(path.join(here, 'diagram-frame.html'), 'utf8').replace('%JS%', `/assets/diagram/${name}`);
  fs.writeFileSync(path.join(dist, 'diagram-frame.html'), html);
  return r.metafile;
}

generatePluginImports();
generateIconsModule();
fs.rmSync(dist, { recursive: true, force: true });
fs.mkdirSync(path.join(dist, 'assets'), { recursive: true });
if (fs.existsSync(path.join(here, 'public'))) fs.cpSync(path.join(here, 'public'), dist, { recursive: true });
copyIcons();

if (watch) {
  const ctx = await esbuild.context({ ...options, plugins: [{ name: 'index', setup(b) { b.onEnd(() => { try { writeIndex(); } catch (e) { console.error(e); } }); } }] });
  await ctx.watch();
  console.log('watching for changes...');
} else {
  const result = await esbuild.build(options);
  const frame = await buildDiagramFrame();
  writeBundledPackages(result.metafile, frame);
  writeIndex(result.metafile);
  console.log('frontend built into web/dist');
}
