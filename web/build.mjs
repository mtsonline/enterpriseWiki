// Builds the frontend into web/dist.
//
// Plugin frontends (plugins/*/web/index.ts) are discovered automatically and
// bundled together with the core, so installing a plugin + rebuilding is all
// that is needed. Output file names contain a content hash (cache busting).
import * as esbuild from 'esbuild';
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const pluginsDir = path.resolve(here, '..', 'plugins');
const dist = path.join(here, 'dist');
const watch = process.argv.includes('--watch');

function generatePluginImports() {
  const dirs = fs.existsSync(pluginsDir) ? fs.readdirSync(pluginsDir).sort() : [];
  const lines = ['// Generated by build.mjs - do not edit.', '// Imports the frontend part of every installed plugin.', 'import { definePluginModule } from "../sdk";', ''];
  const mods = [];
  for (const d of dirs) {
    const entry = path.join(pluginsDir, d, 'web', 'index.ts');
    const manifest = path.join(pluginsDir, d, 'plugin.json');
    if (!fs.existsSync(entry) || !fs.existsSync(manifest)) continue;
    const id = JSON.parse(fs.readFileSync(manifest, 'utf8')).id;
    const name = 'p_' + d.replace(/[^a-zA-Z0-9_]/g, '_');
    lines.push(`import * as ${name} from "../../../plugins/${d}/web/index";`);
    mods.push(`  definePluginModule(${JSON.stringify(id)}, ${name}),`);
  }
  lines.push('', 'export const pluginModules = [', ...mods, '];', '');
  fs.mkdirSync(path.join(here, 'src', 'generated'), { recursive: true });
  fs.writeFileSync(path.join(here, 'src', 'generated', 'plugins.ts'), lines.join('\n'));
}

const options = {
  entryPoints: [path.join(here, 'src', 'main.ts')],
  bundle: true,
  minify: !watch,
  sourcemap: watch ? 'inline' : false,
  format: 'esm',
  // rarely used, large parts (the visual editor) are loaded on first use
  splitting: true,
  chunkNames: 'chunks/[name]-[hash]',
  target: ['es2022', 'chrome111', 'firefox115', 'safari16'],
  outdir: path.join(dist, 'assets'),
  entryNames: 'app',
  alias: { '@ewiki/sdk': path.join(here, 'src', 'sdk.ts') },
  legalComments: 'none',
  // fonts referenced from CSS (e.g. the website template) are copied with a content hash
  loader: { '.woff2': 'file' },
  assetNames: '[name]-[hash]',
  logLevel: 'info',
  metafile: true,
};

// The npm packages that end up in the bundle (for the third-party notices:
// tools/notices includes exactly their license texts).
function writeBundledPackages(meta) {
  const pkgs = new Set();
  for (const input of Object.keys(meta.inputs)) {
    const m = /node_modules\/((?:@[^/]+\/)?[^/]+)\//.exec(input.slice(input.lastIndexOf('node_modules/')));
    if (m) pkgs.add(input.slice(0, input.lastIndexOf('node_modules/')) + 'node_modules/' + m[1]);
  }
  const list = [...pkgs].map((p) => path.relative(here, path.resolve(here, p))).sort();
  fs.mkdirSync(path.join(here, '.build'), { recursive: true });
  fs.writeFileSync(path.join(here, '.build', 'bundled-packages.json'), JSON.stringify(list, null, 1) + '\n');
}

function writeIndex(meta) {
  const js = fs.readFileSync(path.join(dist, 'assets', 'app.js'));
  const css = fs.existsSync(path.join(dist, 'assets', 'app.css')) ? fs.readFileSync(path.join(dist, 'assets', 'app.css')) : Buffer.from('');
  const h = (b) => createHash('sha256').update(b).digest('hex').slice(0, 10);
  const jsName = `app-${h(js)}.js`, cssName = `app-${h(css)}.css`;
  for (const f of fs.readdirSync(path.join(dist, 'assets'))) {
    if (/^app-[0-9a-f]{10}\.(js|css)$/.test(f)) fs.rmSync(path.join(dist, 'assets', f));
  }
  fs.renameSync(path.join(dist, 'assets', 'app.js'), path.join(dist, 'assets', jsName));
  if (css.length) fs.renameSync(path.join(dist, 'assets', 'app.css'), path.join(dist, 'assets', cssName));
  // chunks app.js imports directly are preloaded (no request waterfall)
  const entry = meta && Object.entries(meta.outputs).find(([, o]) => o.entryPoint && o.entryPoint.endsWith('src/main.ts'));
  const preload = (entry ? entry[1].imports : []).filter((i) => i.kind === 'import-statement')
    .map((i) => `<link rel="modulepreload" href="/assets/${path.relative(path.join(dist, 'assets'), path.resolve(i.path)).split(path.sep).join('/')}">`).join('\n  ');
  const html = fs.readFileSync(path.join(here, 'index.html'), 'utf8')
    .replace('%CSS%', `/assets/${cssName}`).replace('%JS%', `/assets/${jsName}`)
    .replace('%PRELOAD%', preload);
  fs.writeFileSync(path.join(dist, 'index.html'), html);
  fs.writeFileSync(path.join(dist, '.gitkeep'), '');
}

generatePluginImports();
fs.rmSync(dist, { recursive: true, force: true });
fs.mkdirSync(path.join(dist, 'assets'), { recursive: true });
if (fs.existsSync(path.join(here, 'public'))) fs.cpSync(path.join(here, 'public'), dist, { recursive: true });

if (watch) {
  const ctx = await esbuild.context({ ...options, plugins: [{ name: 'index', setup(b) { b.onEnd(() => { try { writeIndex(); } catch (e) { console.error(e); } }); } }] });
  await ctx.watch();
  console.log('watching for changes...');
} else {
  const result = await esbuild.build(options);
  writeBundledPackages(result.metafile);
  writeIndex(result.metafile);
  console.log('frontend built into web/dist');
}
